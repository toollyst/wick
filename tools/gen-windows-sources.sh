# Generate the Windows builds of the rust-vmm crates that are written for
# Unix only (src/wick-compat-<crate>/src/windows/), from the upstream source the
# compatibility crate pins.
#
# On Windows wick provides the Unix interfaces these crates use
# (`wick_os::unix`, `wick_os::fd`, the compatibility libc and vmm-sys-util), so
# the generated copy is the upstream source with only these rewrites:
# - every crate: `std::os::unix` -> `wick_os::unix`, `std::os::fd` -> `wick_os::fd`,
#   and `crate::` -> `crate::windows::` (the source is the `windows` module of
#   the compatibility crate); `#[macro_use] extern crate` lines are dropped,
#   the compatibility crate's root declares them (they must be at a root);
# - vm-memory: the Unix mmap backend is used on Windows (its own Windows
#   backend has another interface), and the `rawfd` feature is allowed; in
#   `#[cfg]` attributes only, so `cfg!(...)` keeps upstream's Windows branch.
# - vhost: tests that expect Linux `recvmsg` behaviour expect it on Windows
#   too, where the ScmSocket of vmm-sys-util follows it;
# - upstream tests that need what Windows does not have are compiled out, each
#   listed in EXCLUDED_TESTS with the reason.
# Nothing else changes. Linux and macOS use the upstream crate unchanged.
#
#   tools/gen-windows-sources.sh [--check]
set -euo pipefail
source "$(dirname "$0")/common.sh"
cd "$WICK_ROOT"

# crate  compat dir  source match (tag or rev in the cargo source id of a git
# source, or the version of a crates.io one)
CRATES=(
    "vm-memory    crates/compat/vm-memory      v0.18.0"
    "event-manager crates/compat/event-manager v0.4.2"
    "micro_http   crates/compat/micro-http     7975fe0e59000e8c41cb1d58fbd39ffa102e5b27"
    "vhost        crates/compat/vhost          vhost-v0.17.0"
    "vhost-user-backend tools/vhost-user-blk/compat/vhost-user-backend 0.23.0"
)

# crate  file  test  reason
EXCLUDED_TESTS=(
    "vhost vhost_user/backend_req_handler.rs test_validate_unix_stream_socket_fd Windows AF_UNIX has no datagram sockets, and no /dev/null"
    "vhost vhost_user/frontend.rs test_frontend_set_device_state_fd_no_return_fd it opens /dev/null, which Windows names NUL"
    "vhost vhost_user/frontend.rs test_frontend_set_device_state_fd_with_return_fd it opens /dev/null, which Windows names NUL"
    "micro_http common/mod.rs test_display_connection_error it compares Linux strerror text, and Windows describes OS error codes in its own words"
    "micro_http common/mod.rs test_display_server_error it compares Linux strerror text, and Windows describes OS error codes in its own words"
    "micro_http server.rs test_kill_switch it races the server: once the server thread has handled the kill switch it drops the server, and the connect that follows is refused (the race is upstream's; Windows AF_UNIX connects lose it more often); src/lib.rs tests the kill switch without the race"
)

upstream_src() {
    local name="$1" dir="$2" match="$3"
    cargo metadata --format-version 1 --manifest-path "$dir/Cargo.toml" 2>/dev/null |
        python3 -I -c '
import json, sys
name, match = sys.argv[1], sys.argv[2]
for p in json.load(sys.stdin)["packages"]:
    src = p.get("source") or ""
    git = src.startswith("git+") and match in src
    registry = src.startswith("registry+") and p["version"] == match
    if p["name"] == name and (git or registry):
        print(p["manifest_path"].rsplit("/", 1)[0] + "/src"); break
' "$name" "$match"
}

gen() {
    local name="$1" src="$2" out="$3" match="$4"
    mkdir -p "$out"
    (cd "$src" && find . -name '*.rs' -print) | while read -r f; do
        [[ "$name" == vm-memory && "$f" == ./mmap/windows.rs ]] && continue
        local to="$out/$f"
        [[ "$f" == ./lib.rs ]] && to="$out/mod.rs"
        mkdir -p "$(dirname "$to")"
        { echo "// Generated by tools/gen-windows-sources.sh from $name $match; do not edit."
          cat "$src/$f"; } > "$to"
        perl -pi -e 's/\bstd::os::unix\b/wick_os::unix/g; s/\bstd::os::fd\b/wick_os::fd/g; s/\bcrate::/crate::windows::/g' "$to"
        perl -0pi -e 's/#\[[^\n]*macro_use[^\n]*\]\nextern crate \w+;\n//g' "$to"
        local ex
        for ex in "${EXCLUDED_TESTS[@]}"; do
            read -r ex_crate ex_file ex_test ex_reason <<<"$ex"
            [[ "$ex_crate" == "$name" && "$f" == "./$ex_file" ]] || continue
            grep -q "fn $ex_test()" "$to" || die "$name $ex_file: no test $ex_test"
            REASON="$ex_reason" TEST="$ex_test" perl -0pi -e \
                's/\n([ \t]*)#\[test\]\n(\s*fn $ENV{TEST}\(\))/\n$1\/\/ wick: not on Windows: $ENV{REASON}.\n$1#[cfg(any())]\n$1#[test]\n$2/' "$to"
        done
        if [[ "$name" == vhost ]]; then
            # The Windows ScmSocket receives as Linux recvmsg does, so the
            # tests expect what they expect on Linux.
            perl -pi -e 's/cfg!\(any\(target_os = "linux", target_os = "android"\)\)/cfg!(any(target_os = "linux", target_os = "android", windows))/g' "$to"
        fi
        if [[ "$name" == vm-memory ]]; then
            perl -0pi -e 's/#\[cfg\(all\(target_family = "windows", feature = "rawfd"\)\)\]\ncompile_error!\([^\n]*\n\n//' "$to"
            # Attributes only: `cfg!(...)` expressions are where upstream
            # already chose what to do on Windows (tests that read a system
            # file instead of /dev/zero), and keep that choice.
            perl -pi -e 's/(?<!cfg!\()target_family = "windows"/any()/g; s/(?<!cfg!\()target_family = "unix"/any(unix, windows)/g' "$to"
        fi
    done
}

check=0
[[ "${1:-}" == "--check" ]] && check=1
for entry in "${CRATES[@]}"; do
    read -r name dir match <<<"$entry"
    src="$(upstream_src "$name" "$dir" "$match")"
    [[ -d "$src" ]] || die "upstream $name $match source not found (run cargo fetch)"
    out="$dir/src/windows"
    if ((check)); then
        tmp="$(mktemp -d)"
        gen "$name" "$src" "$tmp" "$match"
        if ! diff -r "$tmp" "$out" >/dev/null; then
            rm -rf "$tmp"
            die "$out is out of date: run $0"
        fi
        rm -rf "$tmp"
        echo "OK: $out matches $name $match"
    else
        rm -rf "$out"
        gen "$name" "$src" "$out" "$match"
        echo "generated $out from $src"
    fi
done
