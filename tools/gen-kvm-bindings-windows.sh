# Generate the Windows build of kvm-bindings (crates/compat/kvm-bindings/src/windows/)
# from the upstream source at the pinned tag.
#
# Windows (LLP64) has a 32-bit `c_ulong`/`c_long`, so the Linux structures would
# change size. The generated copy fixes them to `u64`/`i64`: the Linux x86_64
# layout, which the WHP backend fills. Nothing else changes.
#
#   tools/gen-kvm-bindings-windows.sh [--check]
set -euo pipefail
source "$(dirname "$0")/common.sh"
cd "$WICK_ROOT"

TAG="kvm-ioctls-v0.25.0"
OUT="crates/compat/kvm-bindings/src/windows"

src="$(cargo metadata --format-version 1 --manifest-path crates/compat/kvm-bindings/Cargo.toml 2>/dev/null |
    python3 -I -c '
import json, sys
for p in json.load(sys.stdin)["packages"]:
    if p["name"] == "kvm-bindings" and (p.get("source") or "").startswith("git+") and "'"$TAG"'" in p["source"]:
        print(p["manifest_path"].rsplit("/", 1)[0] + "/src"); break
')"
[[ -d "$src" ]] || die "upstream kvm-bindings $TAG source not found (run cargo fetch)"

gen() {
    local dir="$1"
    mkdir -p "$dir/x86_64"
    cp "$src/serialize.rs" "$dir/serialize.rs"
    for f in mod.rs bindings.rs fam_wrappers.rs nested.rs serialize.rs; do
        cp "$src/x86_64/$f" "$dir/x86_64/$f"
    done
    perl -pi -e 's/::std::os::raw::c_ulong\b/u64/g; s/::std::os::raw::c_long\b/i64/g' \
        "$dir/x86_64/bindings.rs"
    { echo "// Generated by tools/gen-kvm-bindings-windows.sh from kvm-bindings $TAG; do not edit."
      echo "// c_ulong/c_long are u64/i64 (the Linux x86_64 layout)."
      cat "$dir/x86_64/bindings.rs"; } > "$dir/x86_64/bindings.rs.new"
    mv "$dir/x86_64/bindings.rs.new" "$dir/x86_64/bindings.rs"
}

if [[ "${1:-}" == "--check" ]]; then
    tmp="$(mktemp -d)"
    trap 'rm -rf "$tmp"' EXIT
    gen "$tmp"
    diff -r "$tmp" "$OUT" >/dev/null || die "$OUT is out of date: run $0"
    echo "OK: $OUT matches kvm-bindings $TAG"
else
    rm -rf "$OUT"
    gen "$OUT"
    echo "generated $OUT from $src"
fi
